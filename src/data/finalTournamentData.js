function team(name, winner = null) {
  return {
    id: null,
    name,
    code: codes[name] || null,
    flag: flags[name] || null,
    logo: flags[name] || null,
    winner,
    confirmed: true,
  };
}

function archivedMatch({
  id,
  stageCode,
  stage,
  date,
  localDate,
  home,
  away,
  homeGoals,
  awayGoals,
  winner,
  venue,
  city,
  statusShort = "FT",
  statusLong = "Finished",
  elapsed = 90,
  penalties = null,
}) {
  return {
    catalogId: id,
    apiFixtureId: id,
    stageCode,
    stage,
    group: null,
    matchday: null,
    localDate,
    date,
    timezone: "UTC",
    homeTeam: team(home, winner === home),
    awayTeam: team(away, winner === away),
    venue: {
      id: null,
      name: venue,
      fifaName: venue,
      city,
      country: city.includes("Vancouver") ? "Canada" : "United States",
      capacity: null,
    },
    status: {
      long: statusLong,
      short: statusShort,
      elapsed,
    },
    goals: {
      home: homeGoals,
      away: awayGoals,
    },
    score: {
      fullTime: {
        home: homeGoals,
        away: awayGoals,
      },
      penalties,
    },
    dataSource: "Archived FIFA tournament results",
    liveDataAvailable: true,
    archived: true,
  };
}

